import 'dart:async';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:syncbeat/features/audio_sources/youtube_channels.dart';
import 'package:syncbeat/features/audio_sources/youtube_provider.dart';
import 'package:syncbeat/models/spotify_models.dart';
import 'youtube_test.dart' as fixtures;

const channelId = 'UCaaaaaaaaaaaaaaaaaaaaaa';
ChannelEvidence evidence({
  OacStatus oac = OacStatus.unknown,
  bool label = false,
  bool topic = false,
}) => ChannelEvidence(
  channelId: channelId,
  source: Uri.parse('https://example.org/audited-channel-record'),
  oac: oac,
  labelOrDistributor: label,
  topic: topic,
);
Map<String, dynamic> metadata({bool? verified}) => {
  'channel_id': channelId,
  'channel': 'Example Artist',
  'channel_is_verified': ?verified,
};

void main() {
  test('promotional cleanup does not erase a song called Music', () {
    const song = SpotifyTrack(
      id: 'music',
      title: 'Music',
      artists: ['Example Artist'],
      album: '',
      durationMs: 180000,
      isLocal: false,
    );
    final ranked = const YoutubeMatcher().rank(song, [
      fixtures.video(
        'aaaaaaaaaaa',
        title: 'Example Artist - Music (Official Audio)',
      ),
    ]);
    expect(ranked.single.score, greaterThan(85));
  });
  const classifier = YoutubeChannelClassifier();
  test(
    'confirmed OAC requires separate identity-bound evidence; types overlap verification',
    () {
      final info = classifier.classify(
        metadata(verified: true),
        evidence: evidence(oac: OacStatus.confirmed, label: true),
      );
      expect(info.oac, OacStatus.confirmed);
      expect(
        info.types,
        containsAll([
          YoutubeChannelType.officialArtistChannel,
          YoutubeChannelType.labelOrDistributor,
        ]),
      );
      expect(info.verification, ChannelVerification.verified);
      final unrelated = classifier.classify({
        ...metadata(),
        'channel_id': 'UCbbbbbbbbbbbbbbbbbbbbbb',
      }, evidence: evidence(oac: OacStatus.confirmed));
      expect(unrelated.oac, OacStatus.unknown);
    },
  );
  test(
    'generic verification, channel name and spoofed OAC field cannot confirm OAC',
    () {
      final info = classifier.classify({
        ...metadata(verified: true),
        'channel': 'Example Artist Official 🎵',
        'is_oac': true,
      });
      expect(info.oac, OacStatus.unknown);
      expect(info.types, {YoutubeChannelType.verifiedChannel});
    },
  );
  test('Topic requires multiple signals and is not OAC', () {
    final info = classifier.classify({
      ...metadata(),
      'channel': 'Example Artist - Topic',
      'description':
          'Provided to YouTube by Distributor\nAuto-generated by YouTube.',
    });
    expect(info.isTopic, isTrue);
    expect(info.oac, OacStatus.unknown);
    expect(
      classifier.classify({
        ...metadata(),
        'channel': 'Impersonator - Topic',
      }).isTopic,
      isFalse,
    );
  });
  test('distributor uses audited stable channel ID, never name alone', () {
    expect(
      classifier.classify(metadata(), evidence: evidence(label: true)).isLabel,
      isTrue,
    );
    expect(
      classifier.classify({
        ...metadata(),
        'channel': 'Universal Sony VEVO',
      }).isLabel,
      isFalse,
    );
  });
  test(
    'unverified, absent verification and explicitly non-OAC stay distinct',
    () {
      expect(classifier.classify(metadata(verified: false)).types, {
        YoutubeChannelType.unverifiedChannel,
      });
      expect(
        classifier.classify(metadata()).verification,
        ChannelVerification.unknown,
      );
      expect(
        classifier
            .classify(
              metadata(),
              evidence: evidence(oac: OacStatus.notOfficial),
            )
            .oac,
        OacStatus.notOfficial,
      );
    },
  );
  test(
    'exact title and duration beat OAC with incompatible duration or title',
    () {
      final official = classifier.classify(
        metadata(verified: true),
        evidence: evidence(oac: OacStatus.confirmed),
      );
      final results = const YoutubeMatcher().rank(fixtures.track, [
        fixtures.video('aaaaaaaaaaa', duration: 500).withChannelInfo(official),
        fixtures
            .video('bbbbbbbbbbb', title: 'Example Artist - Different Song')
            .withChannelInfo(official),
        fixtures.video('ccccccccccc'),
      ]);
      expect(results.first.video.id, 'ccccccccccc');
      expect(results.first.score, greaterThan(85));
      expect(results[1].score, lessThanOrEqualTo(60));
    },
  );
  for (final version in [
    'live',
    'cover',
    'karaoke',
    'instrumental',
    'sped-up',
    'slowed',
    'nightcore',
    'remix',
  ]) {
    test(
      'penalizes unexpected $version but accepts explicitly requested version',
      () {
        final variant = fixtures.video(
          'aaaaaaaaaaa',
          title: 'Example Artist - Blue Sky $version',
        );
        final requested = SpotifyTrack(
          id: 'x',
          title: 'Blue Sky $version',
          artists: ['Example Artist'],
          album: '',
          durationMs: 180000,
          isLocal: false,
        );
        expect(
          const YoutubeMatcher().rank(requested, [variant]).single.score,
          greaterThan(
            const YoutubeMatcher()
                    .rank(fixtures.track, [variant])
                    .single
                    .score +
                20,
          ),
        );
      },
    );
  }
  test('all featured artists contribute, not only lead artist', () {
    const track = SpotifyTrack(
      id: 'x',
      title: 'Blue Sky (feat. Guest One & Guest Two)',
      artists: ['Example Artist', 'Guest One', 'Guest Two'],
      album: '',
      durationMs: 180000,
      isLocal: false,
    );
    final results = const YoutubeMatcher().rank(track, [
      fixtures.video('aaaaaaaaaaa'),
      fixtures.video(
        'bbbbbbbbbbb',
        title: 'Example Artist - Blue Sky ft. Guest One & Guest Two',
      ),
    ]);
    expect(results.first.video.id, 'bbbbbbbbbbb');
  });
  test('similar scores are ambiguous, deterministic and on scale 0–100', () {
    final results = const YoutubeMatcher().rank(fixtures.track, [
      fixtures.video('bbbbbbbbbbb'),
      fixtures.video('aaaaaaaaaaa'),
    ]);
    expect(results.every((r) => r.ambiguous), isTrue);
    expect(results.first.video.id, 'aaaaaaaaaaa');
    expect(results.every((r) => r.score >= 0 && r.score <= 100), isTrue);
  });
  test(
    'missing metadata earns no points, views and Official text are not proof',
    () {
      final results = const YoutubeMatcher().rank(fixtures.track, [
        YoutubeVideo({'id': 'aaaaaaaaaaa', 'view_count': 999999999}),
      ]);
      expect(results.single.score, 0);
      expect(results.single.durationDifference, isNull);
      expect(results.single.video.channelInfo!.oac, OacStatus.unknown);
    },
  );
  test('weights configurable; invalid weights rejected', () {
    const matcher = YoutubeMatcher(
      weights: YoutubeMatchWeights(
        title: 1,
        artist: 0,
        duration: 0,
        version: 0,
        provenance: 0,
        verification: 0,
      ),
    );
    expect(
      matcher
          .rank(fixtures.track, [fixtures.video('aaaaaaaaaaa')])
          .single
          .score,
      100,
    );
    expect(
      () => const YoutubeMatcher(
        weights: YoutubeMatchWeights(title: -1),
      ).rank(fixtures.track, []),
      throwsArgumentError,
    );
  });
  test(
    'channel cache deduplicates concurrent IDs, caches negatives and expires',
    () async {
      var calls = 0;
      var now = DateTime.utc(2026);
      final cache = YoutubeChannelCache(
        now: () => now,
        ttl: const Duration(seconds: 10),
        loader: (id) async {
          calls++;
          await Future<void>.delayed(Duration.zero);
          return evidence(oac: OacStatus.confirmed);
        },
      );
      final results = await Future.wait([
        cache.lookup(channelId),
        cache.lookup(channelId),
      ]);
      expect(calls, 1);
      expect(results.every((e) => e!.oac == OacStatus.confirmed), isTrue);
      await cache.lookup(channelId);
      expect(calls, 1);
      now = now.add(const Duration(seconds: 11));
      await cache.lookup(channelId);
      expect(calls, 2);
    },
  );
  test(
    'timeout, 429 and network errors fall back to unknown with retry cooldown',
    () async {
      var calls = 0;
      final cache = YoutubeChannelCache(
        loader: (_) async {
          calls++;
          throw Exception('HTTP 429');
        },
      );
      expect(await cache.lookup(channelId), isNull);
      expect(await cache.lookup(channelId), isNull);
      expect(calls, 1);
      final timeout = YoutubeChannelCache(
        timeout: const Duration(milliseconds: 1),
        loader: (_) => Completer<ChannelEvidence?>().future,
      );
      expect(await timeout.lookup(channelId), isNull);
    },
  );
  test('negative channel evidence cached without duplicate requests', () async {
    var calls = 0;
    final cache = YoutubeChannelCache(
      loader: (_) async {
        calls++;
        return null;
      },
    );
    await cache.lookup(channelId);
    await cache.lookup(channelId);
    expect(calls, 1);
    final known = await YoutubeChannelCache.shared.lookup(
      'UC_aEa8K-EOJ3D6gOs7HcyNg',
    );
    expect(known!.labelOrDistributor, isTrue);
  });
  test(
    'association preserves channel_id and URL identity, replacing existing choice',
    () async {
      SharedPreferences.setMockInitialValues({});
      final v = YoutubeVideo({
        ...fixtures.video('aaaaaaaaaaa').metadata,
        ...metadata(verified: true),
      });
      await YoutubeAssociations().save(fixtures.track.id, v);
      final saved = (await YoutubeAssociations().read(fixtures.track.id))!;
      expect(saved.channelId, channelId);
      expect(
        saved.channelUrl.toString(),
        'https://www.youtube.com/channel/$channelId',
      );
      expect(saved.url, v.url);
      await YoutubeAssociations().save(
        fixtures.track.id,
        fixtures.video('bbbbbbbbbbb'),
      );
      expect(
        (await YoutubeAssociations().read(fixtures.track.id))!.id,
        'bbbbbbbbbbb',
      );
    },
  );
}
