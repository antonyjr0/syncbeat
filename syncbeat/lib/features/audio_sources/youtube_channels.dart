import 'dart:async';

enum ChannelVerification { verified, unverified, unknown }

enum OacStatus { confirmed, notOfficial, unknown }

enum YoutubeChannelType {
  officialArtistChannel,
  verifiedChannel,
  topicChannel,
  labelOrDistributor,
  unverifiedChannel,
  unknown,
}

/// Channel identity evidence from a trusted adapter/curated record, never a
/// title, channel name, generic badge or arbitrary video JSON boolean.
class ChannelEvidence {
  const ChannelEvidence({
    required this.channelId,
    required this.source,
    this.oac = OacStatus.unknown,
    this.topic = false,
    this.labelOrDistributor = false,
  });
  final String channelId;
  final Uri source;
  final OacStatus oac;
  final bool topic;
  final bool labelOrDistributor;
}

class YoutubeChannelInfo {
  const YoutubeChannelInfo({
    required this.channelId,
    required this.types,
    required this.verification,
    required this.oac,
    required this.reasons,
  });
  final String? channelId;
  final Set<YoutubeChannelType> types;
  final ChannelVerification verification;
  final OacStatus oac;
  final List<String> reasons;
  bool get isTopic => types.contains(YoutubeChannelType.topicChannel);
  bool get isLabel => types.contains(YoutubeChannelType.labelOrDistributor);
}

class YoutubeChannelClassifier {
  const YoutubeChannelClassifier();
  YoutubeChannelInfo classify(
    Map<String, dynamic> metadata, {
    ChannelEvidence? evidence,
  }) {
    final id = metadata['channel_id'] as String?;
    final trusted =
        id != null &&
        evidence?.channelId == id &&
        evidence!.source.scheme == 'https';
    final verification = switch (metadata['channel_is_verified']) {
      true => ChannelVerification.verified,
      false => ChannelVerification.unverified,
      _ => ChannelVerification.unknown,
    };
    final oac = trusted ? evidence.oac : OacStatus.unknown;
    final name = metadata['channel'] as String? ?? '';
    final description = metadata['description'] as String? ?? '';
    // Topic is an inference with two independent signals, never an OAC claim.
    final topic =
        (trusted && evidence.topic) ||
        (id != null &&
            name.endsWith(' - Topic') &&
            RegExp(
              r'Provided to YouTube by|Auto-generated by YouTube',
              caseSensitive: false,
            ).hasMatch(description));
    final types = <YoutubeChannelType>{
      if (oac == OacStatus.confirmed) YoutubeChannelType.officialArtistChannel,
      if (topic) YoutubeChannelType.topicChannel,
      if (trusted && evidence.labelOrDistributor)
        YoutubeChannelType.labelOrDistributor,
    };
    if (types.isEmpty) {
      types.add(switch (verification) {
        ChannelVerification.verified => YoutubeChannelType.verifiedChannel,
        ChannelVerification.unverified => YoutubeChannelType.unverifiedChannel,
        ChannelVerification.unknown => YoutubeChannelType.unknown,
      });
    }
    return YoutubeChannelInfo(
      channelId: id,
      types: Set.unmodifiable(types),
      verification: verification,
      oac: oac,
      reasons: [
        if (oac == OacStatus.unknown)
          'OAC sconosciuto: yt-dlp non distingue il badge musicale dalla verifica generica.',
        if (trusted) 'Evidenza del canale: ${evidence.source}',
        if (topic && !(trusted && evidence.topic))
          'Topic probabile: suffisso Topic e metadati di distribuzione automatica.',
      ],
    );
  }
}

typedef ChannelEvidenceLoader =
    Future<ChannelEvidence?> Function(String channelId);

/// Shared across searches/dialogs. No additional network calls by default:
/// current yt-dlp output and the public Data API do not expose an OAC field.
class YoutubeChannelCache {
  YoutubeChannelCache({
    this.loader,
    this.ttl = const Duration(hours: 6),
    this.failureTtl = const Duration(minutes: 2),
    this.timeout = const Duration(seconds: 4),
    DateTime Function()? now,
    this.maxEntries = 500,
  }) : _now = now ?? DateTime.now;
  static final shared = YoutubeChannelCache(loader: _curatedEvidence);
  static Future<ChannelEvidence?> _curatedEvidence(String id) async {
    // Small audited identity registry; no name/"VEVO" heuristics or OAC claims.
    if (id == 'UC_aEa8K-EOJ3D6gOs7HcyNg') {
      return ChannelEvidence(
        channelId: id,
        source: Uri.parse('https://ncs.io/'),
        labelOrDistributor: true,
      );
    }
    return null;
  }

  final ChannelEvidenceLoader? loader;
  final Duration ttl, failureTtl, timeout;
  final int maxEntries;
  final DateTime Function() _now;
  final _entries = <String, ({DateTime expires, ChannelEvidence? evidence})>{};
  final _pending = <String, Future<ChannelEvidence?>>{};

  Future<ChannelEvidence?> lookup(String channelId) {
    if (!RegExp(r'^UC[a-zA-Z0-9_-]{22}$').hasMatch(channelId)) {
      return Future.value(null);
    }
    final cached = _entries[channelId];
    if (cached != null && _now().isBefore(cached.expires)) {
      return Future.value(cached.evidence);
    }
    return _pending.putIfAbsent(channelId, () => _fetch(channelId));
  }

  Future<ChannelEvidence?> _fetch(String id) async {
    var lifetime = ttl;
    ChannelEvidence? evidence;
    try {
      evidence = await (loader?.call(id) ?? Future<ChannelEvidence?>.value())
          .timeout(timeout);
      if (evidence?.channelId != id) evidence = null;
    } on Exception {
      // Includes network/429 errors. Negative caching avoids immediate retries.
      lifetime = failureTtl;
    } finally {
      _pending.remove(id);
    }
    if (_entries.length >= maxEntries && _entries.isNotEmpty) {
      _entries.remove(_entries.keys.first);
    }
    _entries[id] = (expires: _now().add(lifetime), evidence: evidence);
    return evidence;
  }
}
